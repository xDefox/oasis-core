/**
 * Сколько миллисекунд симуляции отрабатывать за один кадр.
 *
 * Зачем потолок: requestAnimationFrame в фоновой вкладке не тикает, и первый
 * кадр после возврата приносит delta в десятки секунд. Без потолка игрок
 * прыгнул бы через полкарты.
 *
 * Почему потолок такой большой. 100 мс хватало на 10 fps, но headless-браузер
 * в CI рисует 3–15 fps, то есть кадр длится 70–330 мс. С потолком 100 мс
 * предсказание на медленной машине шло вдвое-втрое медленнее реального
 * времени: сервер (он всегда тикает 20 Гц) уходил вперёд, сверка постоянно
 * тянула игрока за ним, и зонд движения видел «14 м за 1.5 с» при скорости
 * 5 м/с. Это была реальная зависимость симуляции от fps, а не шум зонда.
 *
 * 400 мс покрывают 2.5 fps. Ограничитель в `LocalPlayer.advance` (16 тиков =
 * 800 мс) остаётся выше, поэтому догоняющий шаг — страховка, а не норма.
 */
export const MAX_FRAME_MS = 400;

/** Длительность кадра для симуляции: не больше потолка и не отрицательная. */
export function frameDeltaMs(now: number, lastFrame: number): number {
  const elapsed = now - lastFrame;
  // Часы монотонные, но мусор в них (NaN, откат) останавливает accumulator
  // в LocalPlayer — предсказание замирает, и игрок «залипает».
  if (!Number.isFinite(elapsed) || elapsed < 0) return 0;
  return Math.min(elapsed, MAX_FRAME_MS);
}
